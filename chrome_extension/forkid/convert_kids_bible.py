source_file = "/Users/dayyoung/project/aibible/chrome_extension/json/2thessalonians.json"
target_file = "/Users/dayyoung/project/aibible/chrome_extension/forkid/2thessalonians.json"

# 폴더 생성
os.makedirs(os.path.dirname(target_file), exist_ok=True)

with open(source_file, "r", encoding="utf-8") as f:
    data = json.load(f)

for item in data:
    if item.get("type") == "paragraph text":
        ch = item.get("chapterNumber")
        vs = item.get("verseNumber")
        key = (ch, vs)
        if key in kids_verses:
            item["value"] = kids_verses[key]
        else:
            print(f"Warning: missing verse {ch}:{vs}")

with open(target_file, "w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=4)

print("Conversion complete successfully!")
